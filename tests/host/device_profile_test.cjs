'use strict';
const assert=require('node:assert/strict');
const Profile=require('../../web/device-profile.js');
const base=Profile.clone(Profile.DEFAULT_PROFILE);
assert.deepEqual(Profile.validate(base),[]);
assert.equal(Profile.compatibleWithCurrentFirmware(base),true);
const custom=Profile.normalize({...base,id:'custom-320x240',name:'Landscape panel',display:{...base.display,width:320,height:240,shape:'rectangle',centerX:160,centerY:120}});
assert.deepEqual(Profile.validate(custom),[]);
assert.equal(Profile.compatibleWithCurrentFirmware(custom),false);
assert.ok(Profile.validate({...custom,display:{...custom.display,width:0}}).some(x=>x.includes('Width')));
assert.ok(Profile.validate({...custom,display:{...custom.display,shape:'not-a-shape'}}).some(x=>x.includes('shape')));
assert.ok(Profile.validate({...custom,display:{...custom.display,colorFormat:'RGBA'}}).some(x=>x.includes('color format')));
assert.ok(Profile.validate({...custom,display:{...custom.display,rotation:45}}).some(x=>x.includes('Rotation')));
assert.ok(Profile.validate({...custom,display:{...custom.display,safeArea:{top:'bad',right:0,bottom:0,left:0}}}).some(x=>x.includes('Safe-area')));
assert.ok(Profile.validate({...custom,name:'   '} ).some(x=>x.includes('name')));
assert.ok(Profile.validate({...custom,profileVersion:2}).some(x=>x.includes('version')));
assert.ok(Profile.validate({...custom,id:''}).some(x=>x.includes('ID')));
assert.ok(Profile.validate({...custom,display:{...custom.display,shape:'circle'}}).some(x=>x.includes('equal width')));
assert.ok(Profile.validate({...custom,display:{...custom.display,safeArea:{top:200,bottom:50,left:0,right:0}}}).some(x=>x.includes('no usable')));
const objects=[{id:'a',transform:{x:20,y:30,width:100,height:50},textStyle:{scaleX:1,scaleY:1}}];
const scaled=Profile.migrateObjects(objects,{width:200,height:100},{width:400,height:300},'scale');
assert.deepEqual(scaled[0].transform,{x:40,y:90,width:200,height:150});
assert.equal(scaled[0].textStyle.scaleX,2/3);
assert.equal(scaled[0].textStyle.scaleY,1);
assert.equal(scaled[0].textStyle.fontSize,48);
assert.equal(scaled[0].textStyle.scaleX,2/3);
const kept=Profile.migrateObjects(objects,{width:200,height:100},{width:400,height:300},'keep');
assert.deepEqual(kept[0].transform,objects[0].transform);
console.log('Device Profile validation and migration tests passed.');
